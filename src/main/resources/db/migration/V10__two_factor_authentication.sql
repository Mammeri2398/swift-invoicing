-- V10__two_factor_authentication.sql : double authentification par application (TOTP, RFC 6238)
-- et codes de secours à usage unique.

ALTER TABLE app_user ADD COLUMN totp_secret VARCHAR(64);
ALTER TABLE app_user ADD COLUMN totp_enabled BOOLEAN NOT NULL DEFAULT FALSE;
-- Dernier pas de 30 s accepté : un code déjà utilisé ne peut pas resservir
ALTER TABLE app_user ADD COLUMN totp_last_step BIGINT;

-- Codes de secours, stockés hachés (SHA-256) comme les jetons de réinitialisation
CREATE TABLE user_recovery_code (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    code_hash  VARCHAR(64) NOT NULL,
    used_at    TIMESTAMP
);
CREATE INDEX idx_user_recovery_code_user ON user_recovery_code(user_id);
