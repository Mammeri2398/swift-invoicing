-- V17__invoice_payments.sql : paiements des factures (règlements partiels ou complets).
-- Solde d'une facture = net à payer (TTC + droit de timbre) - avoirs émis - paiements.

CREATE TABLE invoice_payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    paid_on     DATE NOT NULL,
    method      VARCHAR(20),
    reference   VARCHAR(100),
    username    VARCHAR(100),
    created_at  TIMESTAMP NOT NULL
);
CREATE INDEX idx_invoice_payment_invoice ON invoice_payment(invoice_id);

-- Factures déjà marquées payées : un paiement du montant qu'elles restaient devoir, à leur date de paiement
INSERT INTO invoice_payment (invoice_id, amount, paid_on, method, created_at)
SELECT i.id,
       i.total_amount + i.stamp_duty_amount
           - COALESCE((SELECT SUM(c.total_amount) FROM invoice c WHERE c.original_invoice_id = i.id AND c.status = 'ISSUED'), 0),
       CAST(COALESCE(i.paid_at, i.created_at) AS DATE), i.payment_method, COALESCE(i.paid_at, i.created_at)
FROM invoice i
WHERE i.kind = 'INVOICE' AND i.status = 'PAID'
  AND i.total_amount + i.stamp_duty_amount
      - COALESCE((SELECT SUM(c.total_amount) FROM invoice c WHERE c.original_invoice_id = i.id AND c.status = 'ISSUED'), 0) > 0;
