-- V1__init.sql : schema initial pour swift-invoicing (auto-entrepreneur ANAE, Algérie)
-- spring.jpa.hibernate.ddl-auto=validate : le schéma est géré uniquement par Flyway.

CREATE TABLE issuer (
    id                  BIGINT PRIMARY KEY,
    full_name           VARCHAR(255) NOT NULL,
    trade_name          VARCHAR(255),
    address             VARCHAR(255),
    city                VARCHAR(255),
    phone               VARCHAR(50),
    email               VARCHAR(255),
    ae_card_number      VARCHAR(50) NOT NULL,
    nif                 VARCHAR(50) NOT NULL,
    nis                 VARCHAR(50),
    activity_description VARCHAR(500),
    bank_or_ccp_account VARCHAR(100),
    logo                VARCHAR(500)
);

CREATE TABLE client (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                VARCHAR(20) NOT NULL,
    name                VARCHAR(255) NOT NULL,
    address             VARCHAR(255),
    city                VARCHAR(255),
    phone               VARCHAR(50),
    email               VARCHAR(255),
    nif                 VARCHAR(50),
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE invoice_sequence (
    invoice_year    INTEGER PRIMARY KEY,
    last_value      INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE invoice (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number              VARCHAR(50) UNIQUE,
    invoice_year                INTEGER,
    sequence_number             INTEGER,
    client_id                   BIGINT NOT NULL REFERENCES client(id),
    issue_date                  DATE,
    due_date                    DATE,
    status                      VARCHAR(20) NOT NULL,
    payment_method              VARCHAR(20),
    notes                       VARCHAR(1000),
    total_amount                NUMERIC(14,2) NOT NULL DEFAULT 0,
    -- Issuer snapshot (copied at issue time)
    issuer_full_name            VARCHAR(255),
    issuer_trade_name           VARCHAR(255),
    issuer_address              VARCHAR(255),
    issuer_ae_card_number       VARCHAR(50),
    issuer_nif                  VARCHAR(50),
    issuer_nis                  VARCHAR(50),
    issuer_bank_account         VARCHAR(100),
    -- Client snapshot (copied at issue time)
    client_name                 VARCHAR(255),
    client_address              VARCHAR(255),
    client_nif                  VARCHAR(50),
    created_at                  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    issued_at                   TIMESTAMP,
    paid_at                     TIMESTAMP,
    cancelled_at                TIMESTAMP
);

CREATE TABLE invoice_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    position        INTEGER NOT NULL,
    description     VARCHAR(255) NOT NULL,
    unit            VARCHAR(50),
    quantity        NUMERIC(12,3) NOT NULL,
    unit_price      NUMERIC(14,2) NOT NULL,
    line_total      NUMERIC(14,2) NOT NULL
);

-- Indexes
CREATE INDEX idx_invoice_client_id ON invoice(client_id);
CREATE INDEX idx_invoice_status ON invoice(status);
CREATE INDEX idx_invoice_issue_date ON invoice(issue_date);
CREATE INDEX idx_invoice_number ON invoice(invoice_number);
CREATE INDEX idx_invoice_line_invoice_id ON invoice_line(invoice_id);

