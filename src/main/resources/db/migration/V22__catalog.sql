-- V22__catalog.sql : catalogue des produits et services, proposés à la saisie d'une ligne de facture.
-- Une ligne de facture recopie la désignation, l'unité, le prix et la TVA : modifier ou supprimer un
-- article ne change jamais un document déjà établi.
CREATE TABLE catalog_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    unit        VARCHAR(50),
    unit_price  NUMERIC(14,2) NOT NULL,
    vat_rate    NUMERIC(5,2) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP NOT NULL
);

INSERT INTO privilege (code, name, description) VALUES
('MANAGE_CATALOG', 'Gérer le catalogue', 'Créer, modifier et supprimer les produits et services du catalogue');

-- Administrateur keeps every privilege
INSERT INTO profile_privilege (profile_id, privilege_id)
SELECT 1, id FROM privilege WHERE code = 'MANAGE_CATALOG' AND EXISTS (SELECT 1 FROM profile WHERE id = 1);
