-- V24__recurring_invoices.sql : factures récurrentes (loyer, maintenance, abonnement...).
-- Un modèle prépare à chaque échéance une facture brouillon, à vérifier puis émettre : rien n'est émis tout seul.
-- Les échéances sont calculées depuis start_date (start_date + n périodes) : un 31 reste le dernier jour du mois.
CREATE TABLE recurring_invoice (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    -- Supprimer un client sans facture supprime ses modèles
    client_id        BIGINT NOT NULL REFERENCES client(id) ON DELETE CASCADE,
    frequency        VARCHAR(20) NOT NULL,
    start_date       DATE NOT NULL,
    occurrences      INTEGER DEFAULT 0 NOT NULL,
    end_date         DATE,
    due_days         INTEGER,
    payment_method   VARCHAR(30),
    notes            VARCHAR(1000),
    active           BOOLEAN DEFAULT TRUE NOT NULL,
    last_invoice_id  BIGINT REFERENCES invoice(id) ON DELETE SET NULL,
    last_run_at      TIMESTAMP,
    last_error       VARCHAR(500),
    created_at       TIMESTAMP NOT NULL
);

CREATE TABLE recurring_invoice_line (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_invoice_id  BIGINT NOT NULL REFERENCES recurring_invoice(id) ON DELETE CASCADE,
    position              INTEGER NOT NULL,
    description           VARCHAR(255) NOT NULL,
    unit                  VARCHAR(50),
    quantity              NUMERIC(12,3) NOT NULL,
    unit_price            NUMERIC(14,2) NOT NULL,
    vat_rate              NUMERIC(5,2) DEFAULT 0 NOT NULL
);

CREATE INDEX idx_recurring_invoice_client_id ON recurring_invoice(client_id);
CREATE INDEX idx_recurring_invoice_line_parent ON recurring_invoice_line(recurring_invoice_id);
