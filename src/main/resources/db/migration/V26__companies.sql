-- V26__companies.sql : plusieurs sociétés dans une installation.
-- Chaque société a son propre schéma (company_<id>) avec ses tables : émetteur, clients, catalogue, factures,
-- numérotation, paiements, historique, factures récurrentes, réglages email, comptables et de sauvegarde
-- (migrations de db/tenant). Le schéma public garde ce qui est commun à l'installation : utilisateurs, profils,
-- privilèges, licence, la liste des sociétés et les accès des utilisateurs à chacune.
CREATE TABLE company (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(255) NOT NULL,
    schema_name  VARCHAR(63) NOT NULL UNIQUE,
    active       BOOLEAN DEFAULT TRUE NOT NULL,
    created_at   TIMESTAMP NOT NULL
);

-- L'accès d'un utilisateur à une société, avec son profil dans cette société
CREATE TABLE user_company (
    user_id     BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    company_id  BIGINT NOT NULL REFERENCES company(id) ON DELETE CASCADE,
    profile_id  BIGINT NOT NULL REFERENCES profile(id),
    PRIMARY KEY (user_id, company_id)
);

CREATE INDEX idx_user_company_company ON user_company(company_id);

-- Les données existantes deviennent la société n° 1 (tables déplacées dans company_1 par V27)
INSERT INTO company (id, name, schema_name, active, created_at)
SELECT 1, full_name, 'company_1', TRUE, CURRENT_TIMESTAMP FROM issuer WHERE id = 1;
ALTER TABLE company ALTER COLUMN id RESTART WITH 2;

-- Chaque utilisateur garde son profil actuel dans la société n° 1
INSERT INTO user_company (user_id, company_id, profile_id)
SELECT id, 1, profile_id FROM app_user WHERE profile_id IS NOT NULL AND EXISTS (SELECT 1 FROM company WHERE id = 1);
