-- V2__security.sql : tables d'authentification et d'autorisation (profils, privilèges, utilisateurs, reset de mot de passe)

CREATE TABLE privilege (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(100) NOT NULL UNIQUE,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(500)
);

CREATE TABLE profile (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(500)
);

CREATE TABLE profile_privilege (
    profile_id    BIGINT NOT NULL REFERENCES profile(id) ON DELETE CASCADE,
    privilege_id  BIGINT NOT NULL REFERENCES privilege(id) ON DELETE CASCADE,
    PRIMARY KEY (profile_id, privilege_id)
);

CREATE TABLE app_user (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username          VARCHAR(100) NOT NULL UNIQUE,
    email             VARCHAR(255) NOT NULL UNIQUE,
    password          VARCHAR(255) NOT NULL,
    enabled           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    profile_id        BIGINT REFERENCES profile(id)
);

CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      VARCHAR(255) NOT NULL UNIQUE,
    user_id    BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    expiry_date TIMESTAMP NOT NULL
);

-- Indexes
CREATE INDEX idx_app_user_profile ON app_user(profile_id);
CREATE INDEX idx_password_reset_token_user ON password_reset_token(user_id);
CREATE INDEX idx_password_reset_token_token ON password_reset_token(token);
CREATE INDEX idx_profile_privilege_privilege ON profile_privilege(privilege_id);

