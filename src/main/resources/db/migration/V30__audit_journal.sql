-- V30__audit_journal.sql : le journal d'activité (Réglages > Journal d'activité). Qui a fait quoi, quand et d'où :
-- connexions, déconnexions, pages consultées et actions, de toutes les sociétés (company_id, null avant d'en choisir une).
CREATE TABLE audit_event (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMP NOT NULL,
    kind          VARCHAR(20) NOT NULL,
    user_id       BIGINT,
    username      VARCHAR(100),
    company_id    BIGINT,
    company_name  VARCHAR(255),
    method        VARCHAR(10),
    path          VARCHAR(1000),
    status        INTEGER,
    duration_ms   INTEGER,
    handler       VARCHAR(150),
    ip            VARCHAR(64)
);

CREATE INDEX idx_audit_event_occurred ON audit_event(occurred_at);
CREATE INDEX idx_audit_event_company ON audit_event(company_id, occurred_at);
CREATE INDEX idx_audit_event_user ON audit_event(user_id, occurred_at);

INSERT INTO privilege (code, name, description) VALUES
('VIEW_AUDIT', 'Consulter le journal d''activité', 'Voir qui s''est connecté, quelles pages ont été consultées et quelles actions ont été faites');

-- Administrateur keeps every privilege
INSERT INTO profile_privilege (profile_id, privilege_id)
SELECT 1, id FROM privilege WHERE code = 'VIEW_AUDIT' AND EXISTS (SELECT 1 FROM profile WHERE id = 1);
