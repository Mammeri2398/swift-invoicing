-- V7__invoice_audit_trail.sql : historique des actions sur les factures (qui, quoi, quand).
-- Le nom d'utilisateur est stocké en texte (pas de clé étrangère) : l'historique reste lisible
-- même si le compte est supprimé plus tard.

CREATE TABLE invoice_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    action       VARCHAR(20) NOT NULL,
    username     VARCHAR(100),
    occurred_at  TIMESTAMP NOT NULL
);

CREATE INDEX idx_invoice_event_invoice ON invoice_event(invoice_id, occurred_at);

-- Factures existantes : l'historique est reconstitué à partir des dates déjà connues ;
-- l'auteur n'était pas enregistré (username NULL, affiché « inconnu »).
INSERT INTO invoice_event (invoice_id, action, occurred_at)
SELECT id, 'CREATED', created_at FROM invoice;

INSERT INTO invoice_event (invoice_id, action, occurred_at)
SELECT id, 'ISSUED', issued_at FROM invoice WHERE issued_at IS NOT NULL;

INSERT INTO invoice_event (invoice_id, action, occurred_at)
SELECT id, 'PAID', paid_at FROM invoice WHERE paid_at IS NOT NULL;

INSERT INTO invoice_event (invoice_id, action, occurred_at)
SELECT id, 'CANCELLED', cancelled_at FROM invoice WHERE cancelled_at IS NOT NULL;
