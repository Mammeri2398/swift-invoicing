-- db/tenant V1 : les tables d'une société, dans son schéma (company_<id>).
-- État des migrations V1 à V25 de db/migration pour ces tables. La société n° 1 (tables déplacées par V27 sur
-- PostgreSQL) part de cette version de base ; une nouvelle société est créée par ce script.
-- Toute évolution des tables d'une société se fait désormais ici (V2, V3...), appliquée à chaque société.

CREATE TABLE issuer (
    id                    BIGINT PRIMARY KEY,
    full_name             VARCHAR(255) NOT NULL,
    trade_name            VARCHAR(255),
    address               VARCHAR(255),
    city                  VARCHAR(255),
    phone                 VARCHAR(50),
    email                 VARCHAR(255),
    ae_card_number        VARCHAR(50),
    nif                   VARCHAR(50) NOT NULL,
    nis                   VARCHAR(50),
    activity_description  VARCHAR(500),
    bank_or_ccp_account   VARCHAR(100),
    logo_data             BYTEA,
    logo_content_type     VARCHAR(50),
    annual_ceiling        NUMERIC(14,2) DEFAULT 5000000 NOT NULL,
    company_type          VARCHAR(20) DEFAULT 'AUTO_ENTREPRENEUR' NOT NULL,
    legal_form            VARCHAR(50),
    share_capital         NUMERIC(14,2),
    rc_number             VARCHAR(50),
    tax_article           VARCHAR(50),
    vat_mention           VARCHAR(255),
    CONSTRAINT chk_issuer_annual_ceiling CHECK (annual_ceiling > 0)
);

CREATE TABLE client (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(20) NOT NULL,
    name         VARCHAR(255) NOT NULL,
    address      VARCHAR(255),
    city         VARCHAR(255),
    phone        VARCHAR(50),
    email        VARCHAR(255),
    nif          VARCHAR(50),
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    rc_number    VARCHAR(50),
    nis          VARCHAR(50),
    tax_article  VARCHAR(50)
);

CREATE TABLE invoice (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number         VARCHAR(50) UNIQUE,
    invoice_year           INTEGER,
    sequence_number        INTEGER,
    client_id              BIGINT NOT NULL REFERENCES client(id),
    issue_date             DATE,
    due_date               DATE,
    status                 VARCHAR(20) NOT NULL,
    payment_method         VARCHAR(20),
    notes                  VARCHAR(1000),
    total_amount           NUMERIC(14,2) DEFAULT 0 NOT NULL,
    issuer_full_name       VARCHAR(255),
    issuer_trade_name      VARCHAR(255),
    issuer_address         VARCHAR(255),
    issuer_ae_card_number  VARCHAR(50),
    issuer_nif             VARCHAR(50),
    issuer_nis             VARCHAR(50),
    issuer_bank_account    VARCHAR(100),
    client_name            VARCHAR(255),
    client_address         VARCHAR(255),
    client_nif             VARCHAR(50),
    created_at             TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    issued_at              TIMESTAMP,
    paid_at                TIMESTAMP,
    cancelled_at           TIMESTAMP,
    issuer_city            VARCHAR(255),
    issuer_phone           VARCHAR(50),
    issuer_email           VARCHAR(255),
    issuer_company_type    VARCHAR(20),
    issuer_legal_form      VARCHAR(50),
    issuer_share_capital   NUMERIC(14,2),
    issuer_rc_number       VARCHAR(50),
    issuer_tax_article     VARCHAR(50),
    subtotal_amount        NUMERIC(14,2) DEFAULT 0 NOT NULL,
    vat_amount             NUMERIC(14,2) DEFAULT 0 NOT NULL,
    client_rc_number       VARCHAR(50),
    client_nis             VARCHAR(50),
    client_tax_article     VARCHAR(50),
    kind                   VARCHAR(20) DEFAULT 'INVOICE' NOT NULL,
    original_invoice_id    BIGINT REFERENCES invoice(id),
    stamp_duty_amount      NUMERIC(14,2) DEFAULT 0 NOT NULL,
    source_document_id     BIGINT REFERENCES invoice(id),
    accepted_at            TIMESTAMP,
    refused_at             TIMESTAMP,
    issuer_vat_mention     VARCHAR(255)
);

CREATE TABLE invoice_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL,
    description  VARCHAR(255) NOT NULL,
    unit         VARCHAR(50),
    quantity     NUMERIC(12,3) NOT NULL,
    unit_price   NUMERIC(14,2) NOT NULL,
    line_total   NUMERIC(14,2) NOT NULL,
    vat_rate     NUMERIC(5,2) DEFAULT 0 NOT NULL
);

CREATE TABLE invoice_sequence (
    invoice_year  INTEGER PRIMARY KEY,
    last_value    INTEGER DEFAULT 0 NOT NULL
);

CREATE TABLE credit_note_sequence (
    credit_note_year  INTEGER PRIMARY KEY,
    last_value        INTEGER NOT NULL
);

CREATE TABLE document_sequence (
    kind        VARCHAR(20) NOT NULL,
    doc_year    INTEGER NOT NULL,
    last_value  INTEGER NOT NULL,
    PRIMARY KEY (kind, doc_year)
);

CREATE TABLE invoice_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id   BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    action       VARCHAR(20) NOT NULL,
    username     VARCHAR(100),
    occurred_at  TIMESTAMP NOT NULL,
    detail       VARCHAR(500)
);

CREATE TABLE invoice_payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT NOT NULL REFERENCES invoice(id) ON DELETE CASCADE,
    amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    paid_on     DATE NOT NULL,
    method      VARCHAR(20),
    reference   VARCHAR(100),
    username    VARCHAR(100),
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE catalog_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    unit        VARCHAR(50),
    unit_price  NUMERIC(14,2) NOT NULL,
    vat_rate    NUMERIC(5,2) DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE recurring_invoice (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    client_id        BIGINT NOT NULL REFERENCES client(id) ON DELETE CASCADE,
    frequency        VARCHAR(20) NOT NULL,
    start_date       DATE NOT NULL,
    occurrences      INTEGER DEFAULT 0 NOT NULL,
    end_date         DATE,
    due_days         INTEGER,
    payment_method   VARCHAR(30),
    notes            VARCHAR(1000),
    active           BOOLEAN DEFAULT TRUE NOT NULL,
    last_invoice_id  BIGINT REFERENCES invoice(id) ON DELETE SET NULL,
    last_run_at      TIMESTAMP,
    last_error       VARCHAR(500),
    created_at       TIMESTAMP NOT NULL
);

CREATE TABLE recurring_invoice_line (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_invoice_id  BIGINT NOT NULL REFERENCES recurring_invoice(id) ON DELETE CASCADE,
    position              INTEGER NOT NULL,
    description           VARCHAR(255) NOT NULL,
    unit                  VARCHAR(50),
    quantity              NUMERIC(12,3) NOT NULL,
    unit_price            NUMERIC(14,2) NOT NULL,
    vat_rate              NUMERIC(5,2) DEFAULT 0 NOT NULL
);

-- Single-row settings (id = 1), created on first save
CREATE TABLE mail_settings (
    id             BIGINT PRIMARY KEY,
    enabled        BOOLEAN NOT NULL,
    host           VARCHAR(255),
    port           INTEGER,
    security       VARCHAR(20) NOT NULL,
    username       VARCHAR(255),
    password       VARCHAR(255),
    from_address   VARCHAR(255)
);

CREATE TABLE backup_settings (
    id          BIGINT PRIMARY KEY,
    directory   VARCHAR(1000) NOT NULL,
    keep_count  INTEGER NOT NULL
);

CREATE TABLE accounting_settings (
    id                BIGINT PRIMARY KEY,
    customer_account  VARCHAR(20) NOT NULL,
    sales_account     VARCHAR(20) NOT NULL,
    vat_account       VARCHAR(20) NOT NULL,
    stamp_account     VARCHAR(20) NOT NULL,
    bank_account      VARCHAR(20) NOT NULL,
    cash_account      VARCHAR(20) NOT NULL,
    sales_journal     VARCHAR(10) NOT NULL,
    bank_journal      VARCHAR(10) NOT NULL,
    cash_journal      VARCHAR(10) NOT NULL
);

CREATE INDEX idx_invoice_client_id ON invoice(client_id);
CREATE INDEX idx_invoice_issue_date ON invoice(issue_date);
CREATE INDEX idx_invoice_number ON invoice(invoice_number);
CREATE INDEX idx_invoice_status ON invoice(status);
CREATE INDEX idx_invoice_original ON invoice(original_invoice_id);
CREATE INDEX idx_invoice_source ON invoice(source_document_id);
CREATE INDEX idx_invoice_line_invoice_id ON invoice_line(invoice_id);
CREATE INDEX idx_invoice_event_invoice ON invoice_event(invoice_id, occurred_at);
CREATE INDEX idx_invoice_payment_invoice ON invoice_payment(invoice_id);
CREATE INDEX idx_recurring_invoice_client_id ON recurring_invoice(client_id);
CREATE INDEX idx_recurring_invoice_line_parent ON recurring_invoice_line(recurring_invoice_id);

