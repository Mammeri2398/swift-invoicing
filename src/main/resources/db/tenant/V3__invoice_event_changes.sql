-- db/tenant V3 : le détail d'une modification de brouillon dans l'historique : chaque champ changé, avec son
-- ancienne et sa nouvelle valeur, stockées sans mise en forme (nombres, dates ISO, codes) et affichées dans la
-- langue du lecteur.
CREATE TABLE invoice_event_change (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT NOT NULL REFERENCES invoice_event(id) ON DELETE CASCADE,
    position     INTEGER NOT NULL,
    field        VARCHAR(30) NOT NULL,
    line_number  INTEGER,
    old_value    VARCHAR(1000),
    new_value    VARCHAR(1000)
);

CREATE INDEX idx_invoice_event_change_event ON invoice_event_change(event_id, position);
